print(10 + 10)
print(10 - 10)
print(10 * 10)
print(10 / 10)  # osztás eredménye mindig float
print(10 % 3)  # maradékos osztás, maradékot adja vissza
print(10 // 3)  # egész osztás, csak az egész értéket adja vissza
print(10**3)  # hatványozás, 10 a 3
print(10 + 2 * 3)  # 10 + 6 = 16
print((10 + 2) * 3)  # 12 * 3 = 36
print(10 + 2 * 3**3)  # 10 + 2 * 27 = 10 + 54 = 64
